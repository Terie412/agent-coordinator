use crate::Result;
use crate::checkout::Checkout;
use crate::store::{Scope, Store, validate_owner};
use serde_json::{Value, json};
use std::collections::BTreeMap;
use std::env;
use std::io::{self, Read};
use std::path::Path;

const PREFIX: &str = "mcp__agent_coordinator__";
const MATCHER: &str = "^(apply_patch|Bash|mcp__agent_coordinator__(acquire|release))$";

pub fn config(checkout: &Checkout) -> Result<String> {
    let exe = env::current_exe()?;
    let exe = exe.to_str().ok_or("Executable path must be UTF-8")?;
    let root = checkout
        .root
        .to_str()
        .ok_or("Checkout path must be UTF-8")?;
    let unix = |s: &str| format!("'{}'", s.replace('\'', "'\\''"));
    let ps = |s: &str| format!("'{}'", s.replace('\'', "''"));
    let command = json!(format!("{} hook {}", unix(exe), unix(root)));
    let windows = json!(format!("& {} hook {}", ps(exe), ps(root)));
    Ok(format!(
        r#"# Local configuration generated by Agent Coordinator.
[mcp_servers.agent_coordinator]
command = {exe}
args = ["serve", {root}]
tool_timeout_sec = 30

[[hooks.SessionStart]]
matcher = "startup|resume|compact|fork"

[[hooks.SessionStart.hooks]]
type = "command"
command = {command}
command_windows = {windows}
timeout = 5

[[hooks.PreToolUse]]
matcher = {matcher}

[[hooks.PreToolUse.hooks]]
type = "command"
command = {command}
command_windows = {windows}
timeout = 5

[[hooks.SessionEnd]]

[[hooks.SessionEnd.hooks]]
type = "command"
command = {command}
command_windows = {windows}
timeout = 3
"#,
        exe = json!(exe),
        root = json!(root),
        matcher = json!(MATCHER)
    ))
}

pub fn hook(checkout: &Checkout) -> Result<()> {
    let mut input = Vec::new();
    io::stdin().read_to_end(&mut input)?;
    let input: Value = serde_json::from_slice(&input)?;
    let event = input["hook_event_name"].as_str().unwrap_or_default();
    let result = match event {
        "SessionStart" => Some(json!({"hookSpecificOutput": {
            "hookEventName": event,
            "additionalContext": "This checkout uses agent_coordinator. Call acquire with all checkout-relative paths before writing (including shell/script writes) and release exact IDs only after commit or explicit handoff. If blocked, use a bounded wait and re-read after acquiring. Use scope git for index/commit operations and scope checkout for branch switches, merges, and rebases. Commit only the paths you locked. Never release during an in-flight write."
        }})),
        "SessionEnd" => {
            if checkout.database.exists() {
                Store::open(&checkout.database)?.mark_ended(session(&input)?)?;
            }
            None
        }
        "PreToolUse" => match pre_tool_use(checkout, &input) {
            Ok(result) => result,
            Err(error) => Some(deny(error.to_string())),
        },
        _ => None,
    };
    if let Some(result) = result {
        println!("{result}");
    }
    Ok(())
}

fn session(input: &Value) -> Result<&str> {
    validate_owner(input["session_id"].as_str().unwrap_or_default())
}

fn pre_tool_use(checkout: &Checkout, input: &Value) -> Result<Option<Value>> {
    let tool = input["tool_name"].as_str().ok_or("Missing tool_name")?;
    let arguments = &input["tool_input"];
    if matches!(tool.strip_prefix(PREFIX), Some("acquire" | "release")) {
        let mut updated = arguments
            .as_object()
            .ok_or("Missing MCP arguments")?
            .clone();
        updated.insert("owner".into(), json!(session(input)?));
        return Ok(Some(json!({"hookSpecificOutput": {
            "hookEventName": "PreToolUse", "permissionDecision": "allow", "updatedInput": updated
        }})));
    }

    let command = arguments["command"].as_str().ok_or("Missing command")?;
    let (scope, paths) = match tool {
        "apply_patch" => {
            let cwd = arguments["workdir"]
                .as_str()
                .or_else(|| input["cwd"].as_str())
                .ok_or("Missing patch working directory")?;
            (
                Scope::Files,
                checkout.files(&patch_files(command)?, Path::new(cwd))?,
            )
        }
        "Bash" => {
            let Some(scope) = git_scope(command) else {
                return Ok(None);
            };
            (scope, BTreeMap::new())
        }
        _ => return Ok(None),
    };
    let missing = Store::open(&checkout.database)?.missing(session(input)?, scope, &paths)?;
    Ok((!missing.is_empty()).then(|| {
        let targets = missing.iter().take(8).cloned().collect::<Vec<_>>().join(", ");
        deny(format!("Acquire the {} lock(s) with agent_coordinator.acquire before continuing. Missing: {targets}", scope.name()))
    }))
}

fn deny(reason: String) -> Value {
    json!({"hookSpecificOutput": {
        "hookEventName": "PreToolUse", "permissionDecision": "deny", "permissionDecisionReason": reason
    }})
}

fn patch_files(patch: &str) -> Result<Vec<String>> {
    let mut lines = patch.trim().lines();
    if lines.next().map(str::trim) != Some("*** Begin Patch")
        || lines.next_back().map(str::trim) != Some("*** End Patch")
    {
        return Err("Expected an apply_patch patch with standard markers".into());
    }
    let mut files = Vec::new();
    let mut update = false;
    for line in lines {
        let marker_line = if update { line.trim_end() } else { line.trim() };
        if let Some(path) = [
            "*** Add File: ",
            "*** Delete File: ",
            "*** Update File: ",
            "*** Move to: ",
        ]
        .iter()
        .find_map(|marker| marker_line.strip_prefix(marker))
        {
            if !marker_line.starts_with("*** Move to:") {
                update = marker_line.starts_with("*** Update File:");
            }
            files.push(path.to_owned());
        } else if !line.starts_with([' ', '+', '-', '@'])
            && !line.is_empty()
            && marker_line != "*** End of File"
        {
            return Err("Unsupported apply_patch marker. Use standard patch headers.".into());
        }
    }
    Ok(files)
}

fn git_scope(command: &str) -> Option<Scope> {
    // Only direct commands are recognized. Scripts, aliases, and shell composition require cooperation.
    let mut line = command.trim_start();
    if let Some(rest) = line.strip_prefix("& ") {
        line = rest.trim_start();
    }
    let (program, mut rest) = word(line)?;
    if !matches!(program.to_ascii_lowercase().as_str(), "git" | "git.exe") {
        return None;
    }
    let verb = loop {
        let (token, tail) = word(rest)?;
        rest = tail;
        match token {
            "-C" | "-c" => rest = word(rest)?.1,
            "--no-optional-locks" | "--literal-pathspecs" => {}
            _ => break token,
        }
    };
    match verb {
        "add" | "commit" | "update-index" => Some(Scope::Git),
        "am" | "apply" | "checkout" | "cherry-pick" | "clean" | "merge" | "mv" | "pull"
        | "read-tree" | "rebase" | "reset" | "restore" | "revert" | "rm" | "switch" => {
            Some(Scope::Checkout)
        }
        "stash" if !matches!(word(rest).map(|w| w.0), Some("list" | "show")) => {
            Some(Scope::Checkout)
        }
        "worktree" if !matches!(word(rest).map(|w| w.0), Some("list")) => Some(Scope::Checkout),
        _ => None,
    }
}

fn word(line: &str) -> Option<(&str, &str)> {
    let line = line.trim_start();
    let first = line.chars().next()?;
    if matches!(first, '\'' | '"') {
        let content = &line[1..];
        let end = content.find(first)?;
        Some((&content[..end], &content[end + 1..]))
    } else {
        let end = line
            .find(|c: char| c.is_whitespace() || matches!(c, ';' | '|' | '&'))
            .unwrap_or(line.len());
        (end > 0).then(|| line.split_at(end))
    }
}
